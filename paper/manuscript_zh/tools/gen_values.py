#!/usr/bin/env python3
"""data/values.yaml -> build/values.tex (one macro per value, coloured by status) and build/value_list.tex (the
list of values that are still ideal or todo, printed in the writing appendix)."""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
STATUSES = ("real", "ideal", "todo")


def load():
    raw = yaml.safe_load((ROOT / "data/values.yaml").read_text(encoding="utf-8"))
    values = {}
    for key, entry in raw.items():
        if not (isinstance(entry, list) and len(entry) in (2, 3) and entry[1] in STATUSES):
            sys.exit(f"values.yaml: bad entry {key}: {entry!r}")
        value, status = entry[0], entry[1]
        note = entry[2] if len(entry) == 3 else ""
        values[key] = (value, status, note)
    return values


def tex_escape(text):
    return str(text).replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("%", "\\%").replace("&", "\\&") \
        .replace("#", "\\#").replace("$", "\\$").replace("{", "\\{").replace("}", "\\}")


def main():
    values = load()
    out = ROOT / "build"
    out.mkdir(exist_ok=True)
    lines = ["% generated by tools/gen_values.py from data/values.yaml; do not edit"]
    for key, (value, status, _) in values.items():
        items = value if isinstance(value, list) else [value]
        if isinstance(value, list):
            for i, item in enumerate(items, 1):
                lines.append(f"\\defval{{{key}.{i}}}{{{status}}}{{{item}}}")
            lines.append(f"\\defval{{{key}}}{{{status}}}{{{', '.join(str(x) for x in items)}}}")
        else:
            lines.append(f"\\defval{{{key}}}{{{status}}}{{{value}}}")
    counts = {s: sum(1 for v in values.values() if v[1] == s) for s in STATUSES}
    lines += [f"\\def\\NumReal{{{counts['real']}}}", f"\\def\\NumIdeal{{{counts['ideal']}}}",
              f"\\def\\NumTodo{{{counts['todo']}}}"]
    (out / "values.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    rows = ["\\begin{longtable}{p{3.2cm}p{0.9cm}p{4.2cm}p{6.2cm}}", "\\toprule",
            "键名 & 状态 & 当前值 & 说明\\\\", "\\midrule", "\\endhead"]
    for key, (value, status, note) in values.items():
        if status == "real":
            continue
        shown = ", ".join(str(x) for x in value) if isinstance(value, list) else str(value)
        rows.append(f"\\texttt{{{tex_escape(key)}}} & {status} & {tex_escape(shown)} & {tex_escape(note)}\\\\")
    rows += ["\\bottomrule", "\\end{longtable}"]
    (out / "value_list.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"values: {counts['real']} real, {counts['ideal']} ideal, {counts['todo']} todo")


if __name__ == "__main__":
    main()
